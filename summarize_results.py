#!/usr/bin/env python3
from __future__ import annotations
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parent
RESULTS = ROOT / 'results'

def load(name):
    p = RESULTS / name
    return json.loads(p.read_text(encoding='utf-8')) if p.exists() else {}

def main():
    c_raw=load('results.json'); c=c_raw.get('summary', c_raw)
    canon=load('canonicalization_fuzz_summary.json')
    httpcanon=load('http_canonicalization_fuzz_summary.json')
    schema_raw=load('schema_fuzz_summary.json'); schema=schema_raw.get('summary', schema_raw)
    part=load('partition_summary.json')
    gw=load('gateway_summary.json')
    egress=load('egress_gateway_summary.json')
    kms=load('kms_key_release_summary.json')
    ret=load('retrieval_gateway_adapter_summary.json')
    ea=load('ext_authz_adapter_summary.json')
    integ=load('integration_contract_summary.json')
    replay=load('replay_concurrency_summary.json')
    persistent=load('persistent_replay_summary.json')
    base=load('baseline_compare_summary.json')
    pdp=load('pdp_baseline_matrix_summary.json')
    standard=load('standard_policy_baseline_matrix_summary.json')
    bench=load('benchmark_summary.json')
    rows=[]
    pytest_text = (RESULTS / 'run_all_01_stdout.txt').read_text(encoding='utf-8') if (RESULTS / 'run_all_01_stdout.txt').exists() else ''
    import re
    m = re.search(r'(\d+) passed', pytest_text)
    pytest_result = f"{m.group(1)}/{m.group(1)} passed" if m else 'passed'
    rows.append(('Pytest', pytest_result))
    rows.append(('Evaluation vectors', f"{c.get('passed','?')}/{c.get('total_vectors','?')} passed"))
    rows.append(('Denial reason coverage', f"{len(c.get('denial_reason_coverage', []))} codes"))
    rows.append(('Canonicalization equivalent', f"{canon.get('equivalent_digest_stable','?')}/{canon.get('equivalent_cases','?')} stable"))
    rows.append(('Canonicalization distinct', f"{canon.get('distinct_effect_digests_distinct','?')}/{canon.get('distinct_cases','?')} distinguished"))
    rows.append(('Schema-negative fuzz', f"{schema.get('passed','?')}/{schema.get('cases', schema.get('total','?'))} denied"))
    if httpcanon:
        rows.append(('HTTP-envelope canonicalization equivalent', f"{httpcanon.get('equivalent_digest_stable','?')}/{httpcanon.get('equivalent_cases','?')} stable"))
        rows.append(('HTTP-envelope canonicalization distinct', f"{httpcanon.get('distinct_effect_digests_distinct','?')}/{httpcanon.get('distinct_cases','?')} distinguished"))
    rows.append(('Partition/freshness', f"{part.get('passed','?')}/{part.get('total','?')} passed"))
    rows.append(('Capability gateway', f"{gw.get('passed','?')}/{gw.get('total','?')} passed"))
    if egress:
        rows.append(('Egress gateway adapter', f"{egress.get('passed','?')}/{egress.get('cases','?')} passed"))
    rows.append(('Retrieval gateway adapter', f"{ret.get('passed','?')}/{ret.get('cases','?')} passed"))
    rows.append(('ext_authz-shaped adapter', f"{ea.get('passed','?')}/{ea.get('cases','?')} passed"))
    if kms:
        rows.append(('KMS/HSM-shaped key-release gate', f"{kms.get('passed','?')}/{kms.get('cases','?')} passed"))
    if integ:
        rows.append(('Integration contract examples', f"{integ.get('passed','?')}/{integ.get('cases','?')} passed"))
    if pdp:
        o=pdp.get('baselines',{}).get('orprg_reference',{})
        rows.append(('PDP/PEP-shaped baseline matrix', f"cases={pdp.get('cases','?')} ORPRG_correct={o.get('correct','?')} false_allows={o.get('false_allows','?')} false_denies={o.get('false_denies','?')}"))
    if standard:
        o=standard.get('baselines',{}).get('orprg_reference',{})
        rows.append(('Production-adjacent baseline matrix', f"cases={standard.get('cases','?')} ORPRG_correct={o.get('correct','?')} false_allows={o.get('false_allows','?')} false_denies={o.get('false_denies','?')}"))
    rows.append(('Replay concurrency', f"{replay.get('successes','?')} success / {replay.get('replay_denials','?')} replay denials"))
    rows.append(('Persistent replay cache', f"passed={persistent.get('passed','?')} successes={persistent.get('successes','?')} replay_denials={persistent.get('replay_denials','?')}"))
    for r in base.get('rows', []):
        if r.get('model') == 'orprg_v3_2_reference':
            rows.append(('ORPRG synthetic oracle', f"false allows={r.get('false_allow')} false denies={r.get('false_deny')}")); break
    for r in bench.get('rows', []):
        rows.append((f"Benchmark {r.get('mode')} n={r.get('n')}", f"p50={r.get('p50_ms'):.4f} ms p95={r.get('p95_ms'):.4f} ms throughput={r.get('throughput_ops_per_sec'):.2f} ops/s"))
    md=['# Packaged Result Summary','','All results are synthetic reference-evaluation outputs generated by this artifact. They are not production sizing or production non-bypassability claims.','','| Metric | Result |','|---|---|']
    for k,v in rows: md.append(f'| {k} | {v} |')
    (RESULTS/'PACKAGED_RESULT_SUMMARY.md').write_text('\n'.join(md)+'\n', encoding='utf-8')
    (RESULTS/'PACKAGED_RESULT_SUMMARY.json').write_text(json.dumps({'synthetic':True,'rows':[{'metric':k,'result':v} for k,v in rows]}, indent=2, sort_keys=True), encoding='utf-8')
    print(json.dumps({'rows':len(rows),'written':'results/PACKAGED_RESULT_SUMMARY.md'}, indent=2))
if __name__ == '__main__': main()
